  CASE cs.label
    WHEN '0' THEN 'There is no awareness or a significant lack of understanding of the required activities. Key outputs do not exist.'
    WHEN '1' THEN 'Actions for improvement are taken where the persons involved consider them valuable. Even when broadly approved, actions are not always followed up.'
    WHEN '2' THEN 'Agreed improvement actions are usually implemented, and their implementation progress tracked.'
    WHEN '3' THEN 'Agreed improvement actions are consistently managed, their status and progress monitored and their effectiveness reviewed upon completion. Documentation on the approach as well as the result of all activities related to improvements is kept.'
    WHEN '4' THEN 'Beyond the achievement of capability level 3, required activities are managed, monitored and their effectiveness and efficiency evaluated on a regular basis as needed. Regular reviews and audits lead to continual improvement. Outputs are clearly aligned to other outputs.'
  END AS guidance_text
FROM requirements r
JOIN capability_scores cs ON cs.label IN ('0', '1', '2', '3', '4')
WHERE r.code = 'PR14.3' AND r.archived_UTC IS NULL AND cs.archived_UTC IS NULL
ON DUPLICATE KEY UPDATE
  guidance_text = VALUES(guidance_text),
  updated_UTC = UTC_TIMESTAMP(3);

COMMIT;

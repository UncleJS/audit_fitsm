WHERE r.code = 'PR14.1' AND r.archived_UTC IS NULL AND cs.archived_UTC IS NULL
ON DUPLICATE KEY UPDATE
  guidance_text = VALUES(guidance_text),
  updated_UTC = UTC_TIMESTAMP(3);

-- Guidance: PR14.2
INSERT INTO requirement_level_guidance (requirement_id, capability_score_id, guidance_text)
SELECT
  r.id,
  cs.id,
  CASE cs.label
    WHEN '0' THEN 'There is no awareness or a significant lack of understanding of the required activities. Key outputs do not exist.'
    WHEN '1' THEN 'When opportunities for improvement arise, there is a person or group responsible for deciding how to proceed, generally a member of management rather than a group or individual with specific responsibility for improvement. Decisions are more likely based on the opinion or knowledge of the person or group taking the decision than a defined set of criteria.'
    WHEN '2' THEN 'There is some commonly understood approach to evaluating and approving opportunities for improvement, based on a set of criteria. The approach is broadly followed, though not all roles and responsibilities are defined nor decisions and actions to address them always clearly recorded.'
    WHEN '3' THEN 'The approach for evaluation and approval of opportunities for improvement is clearly defined. It is carried whenever new opportunities have been identified, based on defined roles and responsibilities. It is based on clearly identified criteria that seek to maximise the effectiveness the SMS and related capabilities of delivering services according to customer needs and agreed SLAs. Actions to address the identified opportunities for improvement are recorded.'
    WHEN '4' THEN 'Beyond the achievement of capability level 3, required activities are managed, monitored and their effectiveness and efficiency evaluated on a regular basis as needed. Regular reviews and audits lead to continual improvement. Outputs are clearly aligned to other outputs.'
  END AS guidance_text
FROM requirements r
JOIN capability_scores cs ON cs.label IN ('0', '1', '2', '3', '4')
WHERE r.code = 'PR14.2' AND r.archived_UTC IS NULL AND cs.archived_UTC IS NULL
ON DUPLICATE KEY UPDATE
  guidance_text = VALUES(guidance_text),
  updated_UTC = UTC_TIMESTAMP(3);

-- Guidance: PR14.3

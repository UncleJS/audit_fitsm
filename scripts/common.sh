# Shared names and helpers for the lifecycle scripts. Source it, don't run it.
# Variables are used by the scripts that source this file.
# shellcheck disable=SC2034
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT_PREFIX="audit-fitsm"
PROJECT_LABEL_KEY="io.audit-fitsm.project"
PROJECT_LABEL="${PROJECT_LABEL_KEY}=${PROJECT_PREFIX}"

REPO_QUADLET_DIR="${PROJECT_ROOT}/quadlet"
QUADLET_UNIT_DIR="${HOME}/.config/containers/systemd"

# --- Ports (host side, bound to 127.0.0.1). MariaDB 3306 is never published. ---
WEB_PORT=1260
API_PORT=1261
PMA_PORT=1263
CORE_PORTS=("${WEB_PORT}" "${API_PORT}")

# --- Pod / containers ---
POD_NAME="${PROJECT_PREFIX}"
INFRA_CONTAINER="${PROJECT_PREFIX}-infra"
DB_CONTAINER="${PROJECT_PREFIX}-db"
DEV_CONTAINER="${PROJECT_PREFIX}-dev"
PMA_CONTAINER="${PROJECT_PREFIX}-phpmyadmin"

# CI (scripts/ci-strict.sh) names, cleaned up by uninstall too.
CI_POD_NAME="${PROJECT_PREFIX}-ci"
CI_CONTAINERS=("${PROJECT_PREFIX}-dev-ci" "${PROJECT_PREFIX}-db-ci")
CI_VOLUMES=(
  "${PROJECT_PREFIX}-dev-ci"
  "${PROJECT_PREFIX}-db-ci"
  "${PROJECT_PREFIX}-bun-cache-ci"
  "${PROJECT_PREFIX}-exports-ci"
  "${PROJECT_PREFIX}-backups-ci"
)

CI_SECRETS=(
  "${PROJECT_PREFIX}-ci-db-password"
  "${PROJECT_PREFIX}-ci-db-root-password"
  "${PROJECT_PREFIX}-ci-jwt-secret"
)

ALL_PODS=("${POD_NAME}" "${CI_POD_NAME}")
ALL_CONTAINERS=("${DEV_CONTAINER}" "${PMA_CONTAINER}" "${DB_CONTAINER}" "${INFRA_CONTAINER}" "${CI_CONTAINERS[@]}")

# --- systemd user services generated by Quadlet ---
POD_SERVICE="${PROJECT_PREFIX}-pod-pod.service"
DB_SERVICE="${PROJECT_PREFIX}-db.service"
DEV_SERVICE="${PROJECT_PREFIX}-dev.service"
BUILD_SERVICE="${PROJECT_PREFIX}-dev-build.service"
PMA_SERVICE="${PROJECT_PREFIX}-phpmyadmin.service"

VOLUME_NAMES=(
  "${PROJECT_PREFIX}-dev"
  "${PROJECT_PREFIX}-db"
  "${PROJECT_PREFIX}-bun-cache"
  "${PROJECT_PREFIX}-exports"
  "${PROJECT_PREFIX}-backups"
)
VOLUME_SERVICES=()
for _vol in "${VOLUME_NAMES[@]}"; do
  VOLUME_SERVICES+=("${_vol}-volume.service")
done
unset _vol

# Stop order: dependents first.
ALL_SERVICES=(
  "${PMA_SERVICE}"
  "${DEV_SERVICE}"
  "${DB_SERVICE}"
  "${POD_SERVICE}"
  "${BUILD_SERVICE}"
  "${VOLUME_SERVICES[@]}"
)

# --- Quadlet unit files (repo quadlet/ -> ~/.config/containers/systemd/) ---
CORE_QUADLET_FILES=(
  "${PROJECT_PREFIX}-pod.pod"
  "${PROJECT_PREFIX}-db.container"
  "${PROJECT_PREFIX}-dev.container"
  "${PROJECT_PREFIX}-dev.build"
  "${PROJECT_PREFIX}-dev.volume"
  "${PROJECT_PREFIX}-db.volume"
  "${PROJECT_PREFIX}-bun-cache.volume"
  "${PROJECT_PREFIX}-exports.volume"
  "${PROJECT_PREFIX}-backups.volume"
)
BUILD_QUADLET_FILE="${PROJECT_PREFIX}-dev.build"
PMA_QUADLET_FILE="${PROJECT_PREFIX}-phpmyadmin.container"
POD_DROPIN_DIR="${PROJECT_PREFIX}-pod.pod.d"
PMA_DROPIN_FILE="${POD_DROPIN_DIR}/phpmyadmin.conf"

# --- Images ---
DEV_IMAGE="localhost/${PROJECT_PREFIX}-dev:latest"
CI_IMAGE="localhost/${PROJECT_PREFIX}-dev:ci"
BUILT_IMAGES=("${DEV_IMAGE}" "${CI_IMAGE}")
MARIADB_IMAGE="docker.io/library/mariadb:12.3"
PMA_IMAGE="docker.io/library/phpmyadmin:5.2.3"
BUN_IMAGE="docker.io/oven/bun:1.2.22"
UBI_IMAGE="registry.access.redhat.com/ubi10/ubi-minimal:10.3-1795196920"
BASE_IMAGES=("${MARIADB_IMAGE}" "${PMA_IMAGE}" "${BUN_IMAGE}" "${UBI_IMAGE}")

# --- Podman secrets (random values, created by install.sh) ---
DB_PASSWORD_SECRET="${PROJECT_PREFIX}-db-password"
DB_ROOT_PASSWORD_SECRET="${PROJECT_PREFIX}-db-root-password"
JWT_SECRET_SECRET="${PROJECT_PREFIX}-jwt-secret"
ALL_SECRETS=("${DB_PASSWORD_SECRET}" "${DB_ROOT_PASSWORD_SECRET}" "${JWT_SECRET_SECRET}")
# The DB passwords are baked into the data volume at first init, so they are
# kept together with the volumes (removed only with --purge).
DB_SECRETS=("${DB_PASSWORD_SECRET}" "${DB_ROOT_PASSWORD_SECRET}")

log() { printf '[%s] %s\n' "${PROJECT_PREFIX}" "$*"; }
warn() { printf '[%s] WARNING: %s\n' "${PROJECT_PREFIX}" "$*" >&2; }
die() {
  printf '[%s] ERROR: %s\n' "${PROJECT_PREFIX}" "$*" >&2
  exit 1
}

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "missing required command: $1"
}

require_prereqs() {
  require_cmd podman
  require_cmd systemctl
  [[ "${EUID}" -ne 0 ]] || die "run as a normal user; rootless podman only (no sudo)"
  local rootless
  rootless="$(podman info --format '{{.Host.Security.Rootless}}' 2>/dev/null || true)"
  [[ "${rootless}" == "true" ]] || die "podman is not running rootless"
  systemctl --user show-environment >/dev/null 2>&1 \
    || die "no systemd user session (try: loginctl enable-linger \"${USER}\" and log in again)"
}

reload_user_systemd() {
  systemctl --user daemon-reload
}

unit_installed() {
  [[ -f "${QUADLET_UNIT_DIR}/$1" ]]
}

phpmyadmin_installed() {
  unit_installed "${PMA_QUADLET_FILE}"
}

# Copy the core units; render the .build unit with the real repo path.
install_core_quadlets() {
  mkdir -p "${QUADLET_UNIT_DIR}"
  local file
  for file in "${CORE_QUADLET_FILES[@]}"; do
    if [[ "${file}" == "${BUILD_QUADLET_FILE}" ]]; then
      sed "s#@PROJECT_ROOT@#${PROJECT_ROOT}#g" "${REPO_QUADLET_DIR}/${file}" >"${QUADLET_UNIT_DIR}/${file}"
    else
      cp "${REPO_QUADLET_DIR}/${file}" "${QUADLET_UNIT_DIR}/${file}"
    fi
  done
}

install_pma_quadlets() {
  mkdir -p "${QUADLET_UNIT_DIR}/${POD_DROPIN_DIR}"
  cp "${REPO_QUADLET_DIR}/${PMA_QUADLET_FILE}" "${QUADLET_UNIT_DIR}/${PMA_QUADLET_FILE}"
  cp "${REPO_QUADLET_DIR}/${PMA_DROPIN_FILE}" "${QUADLET_UNIT_DIR}/${PMA_DROPIN_FILE}"
}

remove_pma_quadlets() {
  rm -f "${QUADLET_UNIT_DIR}/${PMA_QUADLET_FILE}" "${QUADLET_UNIT_DIR}/${PMA_DROPIN_FILE}"
  rmdir "${QUADLET_UNIT_DIR}/${POD_DROPIN_DIR}" 2>/dev/null || true
}

remove_all_quadlets() {
  local file
  for file in "${CORE_QUADLET_FILES[@]}"; do
    rm -f "${QUADLET_UNIT_DIR}/${file}"
  done
  remove_pma_quadlets
  rm -rf "${QUADLET_UNIT_DIR:?}/${POD_DROPIN_DIR}"
}

random_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    head -c 32 /dev/urandom | base64 | tr -d '\n=+/'
  fi
}

secret_exists() {
  podman secret exists "$1" 2>/dev/null
}

ensure_secrets() {
  local name
  for name in "${ALL_SECRETS[@]}"; do
    if secret_exists "${name}"; then
      log "secret ${name} exists (kept)"
    else
      random_secret | podman secret create --label "${PROJECT_LABEL}" "${name}" - >/dev/null
      log "secret ${name} created"
    fi
  done
}

require_secrets() {
  local name
  for name in "${ALL_SECRETS[@]}"; do
    secret_exists "${name}" || die "podman secret ${name} is missing; run scripts/install.sh"
  done
}

require_installed() {
  local file
  for file in "${CORE_QUADLET_FILES[@]}"; do
    unit_installed "${file}" || die "Quadlet unit ${file} is not installed; run scripts/install.sh"
  done
}

# Ports this project's own pod already publishes don't count as conflicts.
preflight_ports() {
  local ports=("${CORE_PORTS[@]}")
  if phpmyadmin_installed || [[ "${WITH_PMA:-false}" == "true" ]]; then
    ports+=("${PMA_PORT}")
  fi
  "${PROJECT_ROOT}/scripts/preflight-ports.sh" --allow-pod "${POD_NAME}" "${ports[@]}"
}

stop_services() {
  local svc
  for svc in "${ALL_SERVICES[@]}"; do
    systemctl --user stop "${svc}" >/dev/null 2>&1 || true
  done
}

reset_failed_services() {
  local svc
  for svc in "${ALL_SERVICES[@]}"; do
    systemctl --user reset-failed "${svc}" >/dev/null 2>&1 || true
  done
}

print_urls() {
  printf '  Web UI:     http://127.0.0.1:%s\n' "${WEB_PORT}"
  printf '  API:        http://127.0.0.1:%s\n' "${API_PORT}"
  if phpmyadmin_installed; then
    printf '  phpMyAdmin: http://127.0.0.1:%s\n' "${PMA_PORT}"
  fi
}
